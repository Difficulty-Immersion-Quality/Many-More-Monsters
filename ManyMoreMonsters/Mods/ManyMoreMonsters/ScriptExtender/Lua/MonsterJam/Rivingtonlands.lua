local function CreateAct3Mimics()
    local Act3ChestList = { Act3Chest1, Act3Chest2, Act3Chest3, Act3Chest4, Act3Chest5, Act3Chest6, Act3Chest7,
        Act3Chest8, Act3Chest9, Act3Chest10,
